/**
 * Per-page metadata: title/description plus canonical URL, Open Graph and Twitter card.
 * `path` is the route with trailing slash, e.g. "/shaho/"; `og` picks the share image (defaults to the home card).
 */
export function pageMetadata({
  path,
  title,
  description,
  og = "home",
  noindex = false,
}: {
  path: string;
  title: string;
  description: string;
  og?: OgKey;
  noindex?: boolean;
}): Metadata {
  const fullTitle = path === "/" ? SITE_NAME : `${title}｜${SITE_NAME}`;
  const image = ogImage(og);
  return {
    title: path === "/" ? { absolute: SITE_NAME } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      siteName: SITE_NAME,
      locale: SITE_LOCALE,
      type: "website",
      url: path,
      title: fullTitle,
      description,
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [image],
    },
    ...(noindex && { robots: { index: false, follow: true } }),
  };
}

